class Screen < ApplicationRecord
  # ============================================================================
  # Screen（スクリーン）モデル
  # ============================================================================
  # 劇場内の「上映室」を表すモデルです。
  # 1つのスクリーンは複数の座席（sheets）と複数の上映スケジュール（schedules）を持ちます。
  #
  # 例: 「スクリーン1」→ 座席A1〜A10, B1〜B10... + 複数の上映スケジュール
  # ============================================================================

  # ----------------------------------------------------------------------------
  # 関連（Association）
  # ----------------------------------------------------------------------------

  # 劇場との関連
  # - 1つのスクリーンは必ず1つの劇場に属する（N:1の関係）
  # - theater_id が必須（外部キー制約）
  belongs_to :theater

  # 座席との関連
  # - 1つのスクリーンは複数の座席を持つ（1:Nの関係）
  # - 座席は行・列の情報を持つ（例: A1, A2, B1, B2...）
  # - スクリーン削除時に関連する座席も自動削除される
  has_many :sheets, dependent: :destroy

  # 上映スケジュールとの関連
  # - 1つのスクリーンは複数の上映スケジュールを持つ（1:Nの関係）
  # - 同じスクリーンで異なる時間帯に異なる映画を上映可能
  # - スクリーン削除時に関連するスケジュールも自動削除される
  has_many :schedules, dependent: :destroy

  # ----------------------------------------------------------------------------
  # バリデーション（Validation）
  # ----------------------------------------------------------------------------

  # スクリーン名のバリデーション
  validates :name,
            # 必須チェック: スクリーン名は空ではいけない
            presence: true,
            # 一意性チェック: 同じ劇場内でスクリーン名の重複を防ぐ
            uniqueness: {
              # スコープ: theater_id をスコープとして使用
              # → 異なる劇場では同じスクリーン名でもOK
              # → 同じ劇場内では同じスクリーン名はNG
              scope: :theater_id,
              # 大文字小文字を区別しない
              # → "スクリーン1" と "スクリーン１" は同じとみなす
              case_sensitive: false,
              # カスタムエラーメッセージ
              message: 'は同じ劇場内で一意になるよう設定してください'
            }

  # スクリーン作成時に標準座席(3x5)を自動生成
  # - 小規模構成をデフォルトとし、運用/将来拡張で増席する想定
  after_create :generate_default_sheets

  # 例:
  # ✅ OK: 劇場Aに「スクリーン1」、劇場Bに「スクリーン1」 → 異なる劇場なのでOK
  # ❌ NG: 劇場Aに「スクリーン1」を2つ作成 → 同じ劇場内で重複なのでNG
  # ❌ NG: スクリーン名が空 → 必須チェックでNG
  private

  # 標準レイアウトの定義
  # - DEFAULT_ROWS: 行ラベル（A, B, C）
  # - DEFAULT_COLUMNS: 列番号（1..5）
  # - 文字列/数値配列に変換してfreezeし、実行時に上書きされない不変データとして扱う
  DEFAULT_ROWS = ('A'..'C').to_a.freeze
  DEFAULT_COLUMNS = (1..5).to_a.freeze

  def generate_default_sheets
    # スクリーン作成時に標準座席(3x5)を自動生成する。
    # 重要なポイント:
    # - idempotent（冪等）: 既に存在する座席は再作成せず、欠けている組み合わせのみを補完する。
    # - 一意性の考え方: row と column の組み合わせがそのスクリーン内で一意になる想定。
    #   DBにユニーク制約が無くても find_or_create_by! により二重作成を避けられる（競合がなければ）。
    #   もし同時作成が懸念される高負荷環境なら、DB側ユニークインデックスの追加を検討する。
    DEFAULT_ROWS.each do |row|
      DEFAULT_COLUMNS.each do |column|
        # 指定の row/column が未登録なら作成、登録済みなら既存を返す。
        # 例) A-1, A-2, ... C-5 の全15席を埋める。
        sheets.find_or_create_by!(row: row, column: column)
      end
    end
  end
end
